import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const packageRoot = resolve(here, '..')
const lexiconPath = resolve(
  packageRoot,
  '..',
  'lexicon',
  'social',
  'craftsky',
  'feed',
  'post.json',
)
const outputPath = resolve(
  packageRoot,
  'src',
  'generated',
  'craftsky-feed-post.ts',
)

const schema = JSON.parse(await readFile(lexiconPath, 'utf8'))
const record = schema.defs.main.record
const externalImport = schema.defs.externalImport
const image = schema.defs.image
const aspectRatio = schema.defs.aspectRatio
if (
  schema.id !== 'social.craftsky.feed.post' ||
  record.properties.externalImport?.ref !== '#externalImport' ||
  !externalImport.required?.includes('source')
) {
  throw new Error('Lexicon is missing the approved externalImport contract')
}

const source = externalImport.properties.source
const text = record.properties.text
const images = record.properties.images
const imageBlob = image.properties.image
const imageAlt = image.properties.alt

const generated = `// Generated by scripts/generate-lexicon-contract.mjs. Do not edit.

export const CRAFTSKY_POST_COLLECTION = ${JSON.stringify(schema.id)} as const
export const INSTAGRAM_IMPORT_SOURCE = ${JSON.stringify(source.knownValues[0])} as const
export const EXTERNAL_IMPORT_SOURCE_MAX_BYTES = ${source.maxLength} as const
export const POST_TEXT_MAX_BYTES = ${text.maxLength} as const
export const POST_TEXT_MAX_GRAPHEMES = ${text.maxGraphemes} as const
export const POST_IMAGE_MAX_COUNT = ${images.maxLength} as const
export const POST_IMAGE_MAX_BYTES = ${imageBlob.maxSize} as const
export const POST_IMAGE_ACCEPT = ${JSON.stringify(imageBlob.accept)} as const
export const POST_IMAGE_ALT_MAX_BYTES = ${imageAlt.maxLength} as const
export const POST_IMAGE_ALT_MAX_GRAPHEMES = ${imageAlt.maxGraphemes} as const
export const POST_ASPECT_RATIO_MINIMUM = ${aspectRatio.properties.width.minimum} as const

export interface ExternalImportRecord {
  readonly source: string
}

export interface CraftskyImageRecord {
  readonly image: unknown
  readonly alt?: string
  readonly aspectRatio?: {
    readonly width: number
    readonly height: number
  }
}

export interface CraftskyFeedPostRecord {
  readonly $type: typeof CRAFTSKY_POST_COLLECTION
  readonly text: string
  readonly facets?: readonly unknown[]
  readonly images?: readonly CraftskyImageRecord[]
  readonly createdAt: string
  readonly externalImport?: ExternalImportRecord
}

const encoder = new TextEncoder()
const segmenter = new Intl.Segmenter('en', { granularity: 'grapheme' })
const acceptedImageMimes = new Set<string>(POST_IMAGE_ACCEPT)

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

function hasOnlyKeys(
  record: Record<string, unknown>,
  allowed: readonly string[],
): boolean {
  return Object.keys(record).every((key) => allowed.includes(key))
}

function isValidFacet(value: unknown, textBytes: number): boolean {
  if (!isRecord(value) || !hasOnlyKeys(value, ['index', 'features'])) return false
  if (!isRecord(value.index) || !hasOnlyKeys(value.index, ['byteStart', 'byteEnd'])) {
    return false
  }
  const start = value.index.byteStart
  const end = value.index.byteEnd
  if (
    !Number.isInteger(start) ||
    !Number.isInteger(end) ||
    (start as number) < 0 ||
    (end as number) <= (start as number) ||
    (end as number) > textBytes ||
    !Array.isArray(value.features) ||
    value.features.length !== 1
  ) {
    return false
  }
  const feature: unknown = value.features[0]
  if (!isRecord(feature)) return false
  if (feature.$type === 'app.bsky.richtext.facet#tag') {
    return (
      hasOnlyKeys(feature, ['$type', 'tag']) &&
      typeof feature.tag === 'string' &&
      feature.tag.length > 0 &&
      encoder.encode(feature.tag).byteLength <= 640 &&
      [...segmenter.segment(feature.tag)].length <= 64
    )
  }
  if (feature.$type === 'app.bsky.richtext.facet#link') {
    if (
      !hasOnlyKeys(feature, ['$type', 'uri']) ||
      typeof feature.uri !== 'string' ||
      encoder.encode(feature.uri).byteLength > 8192
    ) {
      return false
    }
    try {
      const uri = new URL(feature.uri)
      return uri.protocol === 'http:' || uri.protocol === 'https:'
    } catch {
      return false
    }
  }
  return false
}

function isValidBlob(value: unknown): boolean {
  if (!isRecord(value)) return false
  const mimeType = value.mimeType
  const size = value.size
  const ref = value.ref
  const typed = value.$type === 'blob'
  const instanceLike = value.$type === undefined
  return (
    (typed || instanceLike) &&
    typeof mimeType === 'string' &&
    acceptedImageMimes.has(mimeType) &&
    Number.isInteger(size) &&
    (size as number) >= 0 &&
    (size as number) <= POST_IMAGE_MAX_BYTES &&
    typeof ref === 'object' &&
    ref !== null
  )
}

function isValidImage(value: unknown): value is CraftskyImageRecord {
  if (!isRecord(value) || !hasOnlyKeys(value, ['image', 'alt', 'aspectRatio'])) {
    return false
  }
  if (!isValidBlob(value.image)) return false
  if (
    value.alt !== undefined &&
    (typeof value.alt !== 'string' ||
      encoder.encode(value.alt).byteLength > POST_IMAGE_ALT_MAX_BYTES ||
      [...segmenter.segment(value.alt)].length >
        POST_IMAGE_ALT_MAX_GRAPHEMES)
  ) {
    return false
  }
  if (value.aspectRatio !== undefined) {
    if (
      !isRecord(value.aspectRatio) ||
      !hasOnlyKeys(value.aspectRatio, ['width', 'height']) ||
      !Number.isInteger(value.aspectRatio.width) ||
      !Number.isInteger(value.aspectRatio.height) ||
      (value.aspectRatio.width as number) < POST_ASPECT_RATIO_MINIMUM ||
      (value.aspectRatio.height as number) < POST_ASPECT_RATIO_MINIMUM
    ) {
      return false
    }
  }
  return true
}

export function isValidExternalImport(value: unknown): value is ExternalImportRecord {
  if (!isRecord(value)) return false
  const record = value
  return (
    Object.keys(record).every((key) => key === 'source') &&
    typeof record.source === 'string' &&
    encoder.encode(record.source).byteLength <= EXTERNAL_IMPORT_SOURCE_MAX_BYTES
  )
}

export function isValidCraftskyFeedPostRecord(
  value: unknown,
): value is CraftskyFeedPostRecord {
  if (!isRecord(value)) return false
  const record = value
  if (
    !hasOnlyKeys(record, [
      '$type',
      'text',
      'facets',
      'images',
      'createdAt',
      'externalImport',
    ])
  ) {
    return false
  }
  const textBytes =
    typeof record.text === 'string' ? encoder.encode(record.text).byteLength : 0
  if (
    record.$type !== CRAFTSKY_POST_COLLECTION ||
    typeof record.text !== 'string' ||
    textBytes > POST_TEXT_MAX_BYTES ||
    [...segmenter.segment(record.text)].length > POST_TEXT_MAX_GRAPHEMES ||
    typeof record.createdAt !== 'string' ||
    !Number.isFinite(Date.parse(record.createdAt))
  ) {
    return false
  }
  if (
    record.externalImport !== undefined &&
    !isValidExternalImport(record.externalImport)
  ) {
    return false
  }
  if (
    record.facets !== undefined &&
    (!Array.isArray(record.facets) ||
      !record.facets.every((facet) => isValidFacet(facet, textBytes)))
  ) {
    return false
  }
  if (
    record.images !== undefined &&
    (!Array.isArray(record.images) ||
      record.images.length > POST_IMAGE_MAX_COUNT ||
      !record.images.every(isValidImage))
  ) {
    return false
  }
  if (record.text.length === 0 && (!record.images || record.images.length === 0)) {
    return false
  }
  return true
}
`

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '')
  if (current !== generated) {
    throw new Error(
      'Generated web Lexicon contract is stale. Run npm run generate.',
    )
  }
} else {
  await writeFile(outputPath, generated)
}
