#!/usr/bin/env python3
"""Generate client data and the public safety guide from one public-only source."""
import argparse
import html
import json
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]


def artifacts():
    data = json.loads((ROOT / 'shared/safety-support.json').read_text())
    for resource in data['resources']:
        url = urlsplit(resource['url'])
        if url.scheme != 'https' or url.query or url.fragment or url.username or url.password:
            raise ValueError('Support destinations must be fixed public HTTPS URLs without routing data')
        if not ((url.hostname or '').endswith('.gov.uk') or url.hostname.endswith('.nhs.uk') or url.hostname in {'www.nhs.uk', 'www.nhsinform.scot'}):
            raise ValueError('Unreviewed support destination')
    encoded = json.dumps(data, ensure_ascii=False, indent=2) + '\n'
    dart = '// Generated by scripts/generate-safety-guide.py. Do not edit.\n// ignore_for_file: type=lint\nconst Map<String, dynamic> safetyGuide = ' + encoded.rstrip().replace('$', r'\$') + ';\n'
    escape = html.escape
    parts = [f'<h1>{escape(data["title"])}</h1>', f'<p>{escape(data["intro"])}</p>', f'<p class="notice">{escape(data["urgent"])}</p>', f'<h2 id="support">{escape(data["supportTitle"])}</h2>', f'<p>{escape(data["supportIntro"])}</p>']
    for item in data['resources']:
        parts.append(f'<section><h3><a href="{escape(item["url"], quote=True)}" target="_blank" rel="noopener noreferrer" referrerpolicy="no-referrer">{escape(item["title"])} ↗</a></h3><p><strong>{escape(item["scope"])}</strong> — {escape(item["body"])}</p></section>')
    parts.extend([f'<p>{escape(data["outsideUK"])}</p>', f'<h2>{escape(data["youngTitle"])}</h2><p>{escape(data["youngBody"])}</p>', f'<h2>{escape(data["stepsTitle"])}</h2>', '<ol class="safety-steps">'])
    for item in data['steps']:
        parts.append(f'<li><span class="step-symbol" aria-hidden="true">{escape(item["symbol"])}</span><h3>{escape(item["title"])}</h3><p>{escape(item["body"])}</p></li>')
    parts.append('</ol>')
    for name in ['messages', 'parents']:
        parts.append(f'<h2>{escape(data[name+"Title"])}</h2><p>{escape(data[name+"Body"])}</p>')
    parts.extend([f'<p>{escape(data["limits"])}</p>', f'<p>Resources reviewed: {escape(data["reviewed"])}</p>'])
    page = '<!doctype html>\n<html lang="en-GB"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="referrer" content="no-referrer"><title>Safety and support — CraftSky</title><link rel="stylesheet" href="/styles.css"><link rel="canonical" href="https://craftsky.social/safety"><style>.safety-steps{display:grid;gap:1rem;list-style:none;padding:0}.safety-steps li{border:2px solid currentColor;border-radius:1rem;padding:1rem}.step-symbol{display:inline-grid;place-items:center;width:2.5rem;height:2.5rem;border:2px solid currentColor;border-radius:50%;font-size:1.5rem}.notice{font-weight:600}@media(min-width:700px){.safety-steps{grid-template-columns:repeat(3,1fr)}}</style></head><body><a class="skip-link" href="#main">Skip to main content</a><header class="page-header"><div class="container"><a href="/">CraftSky home</a></div></header><main id="main" class="legal"><article class="container container--narrow">' + '\n'.join(parts) + '</article></main><footer class="container"><nav aria-label="Information"><a href="/reporting">Reporting</a> · <a href="/privacy">Privacy</a> · <a href="/terms">Terms</a></nav></footer></body></html>\n'
    return {'app/lib/safety/guide_data.dart': dart, 'web-client/src/lib/features/safety/guide-data.json': encoded, 'web/safety.html': page}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in artifacts().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Safety guide artifact is stale: {name}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == '__main__':
    main()
